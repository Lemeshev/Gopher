  const entries = [];
  Object.keys(Q).forEach(id => {
    Q[id].forEach(text => entries.push({ id: id, text: text }));
  });

  // Подстраховка: ключи тем, которых нет в каталоге, тоже попадают в индекс —
  // вдруг захочешь добавить новую тему, не прописывая весь список фраз.
