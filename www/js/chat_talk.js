  function mathLine(n) {
    const parts = n.split(' ').filter(Boolean);
    let a = null, op = '', b = null;
    for (let i = 0; i < parts.length; i++) {
      const v = wordNum(parts[i]);
      if (v !== null && a === null) a = v;
      else if (v !== null && op && b === null) b = v;
      else if (/плюс|минус|умнож/.test(parts[i])) op = parts[i];
    }
    if (a === null || b === null || !op) return '';
    let r = null;
    if (/плюс/.test(op)) r = a + b;
    else if (/минус/.test(op)) r = a - b;
    else if (/умнож/.test(op)) r = a * b;
    if (r === null || r < 0 || r > 10) return 'Такой счёт я в уме не держу. Могу сложить маленькие числа до десяти.';
    return 'Получается ' + (NUMW[r] || String(r)) + '.';
  }

