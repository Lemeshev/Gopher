  var bank = null;
  function ensureBank() {
    if (bank) return bank;
    bank = [];
    var seen = {};
    function add(line) {
      line = cleanReply(line);
      if (!line || line.length < 20 || line.length > 180 || seen[line]) return;
      if (/ловлю знакомые|назови тему|слышу фразу целиком|не прыгаю|про «|без слёз|проиграл навсегда|фонарик и плед/.test(line)) return;
      seen[line] = 1;
      bank.push({ line: line, v: mixDense(line) });
    }
    var about = (typeof window !== 'undefined' && window.CHAT_TALK && window.CHAT_TALK.about) || {};
    Object.keys(about).forEach(function (k) { (about[k] || []).forEach(add); });
    ensureDocs().forEach(function (d) { add(d.reply); });
    return bank;
  }

  function bestBank(scene, qv) {
    var rows = ensureBank();
    var best = null;
    for (var i = 0; i < rows.length; i++) {
      if (!unused(scene, rows[i].line)) continue;
      var s = cosD(qv, rows[i].v);
      if (!best || s > best.s) best = { s: s, line: rows[i].line };
    }
    return best;
  }

  function composeReply(scene, n) {
    var qv = mixDense(n);
    if (scene.memDense) {
      var mixed = new Float32Array(DIM);
      for (var i = 0; i < DIM; i++) mixed[i] = scene.memDense[i] * 0.35 + qv[i] * 0.65;
      qv = mixed;
    }
    scene.memDense = mixDense(n);
    var named = null;
    var mq = stemVector(n);
    var move = null;
    MOVES.forEach(function (m) {
      var dot = 0, k;
      for (k in mq) if (m.v[k]) dot += Math.min(mq[k], m.v[k]);
      if (!move || dot > move.s) move = { s: dot, row: m };
    });
    var line;
    var askedStory = move && move.row.id === 'tell' && move.s >= 1;
    var aboutSelf = n.indexOf('о себе') !== -1 || n.indexOf('про себя') !== -1 || (' ' + n + ' ').indexOf(' себе ') !== -1;
    if (aboutSelf) {
      line = familyLine(scene, 'who', qv);
    } else if (askedStory) {
      line = storyLine(scene, qv);
    } else if (move && move.s >= 1 && FAMILIES[move.row.id]) {
      line = familyLine(scene, move.row.id, qv);
    } else {
      var hit = bestBank(scene, qv);
      var share = false;
      var want = {};
      normalize(n).split(' ').forEach(function (w) {
        var s = stem(w);
        if (s && s.length >= 5) want[s] = 1;
      });
      if (hit) {
        normalize(hit.line).split(' ').forEach(function (w) {
          var s = stem(w);
          if (want[s]) share = true;
        });
      }
      var words = normalize(n).split(' ').filter(Boolean);
      if ((words.indexOf('как') !== -1 && words.indexOf('ты') !== -1) || words.indexOf('настроен') !== -1) {
        line = familyLine(scene, 'mood', qv);
      } else if (hit && hit.s >= 0.55 && share) line = hit.line;
      else line = familyLine(scene, 'listen', qv);
    }
    return rememberLine(scene, line);
  }

  function pickFresh(scene, arr) {
    scene.said = scene.said || {};
    var start = scene.embedN || 0;
    var line = arr[start % arr.length];
    for (var k = 0; k < arr.length; k++) {
      var tryLine = arr[(start + k) % arr.length];
      if (!scene.said[tryLine]) { line = tryLine; break; }
    }
    scene.said[line] = 1;
    scene.embedN = start + 1;
    return line;
  }

  function pickLine(scene, id) {
    var arr = MOVE_LINES[id] || MOVE_LINES.listen;
    scene.embedMove = id;
    var line = pickFresh(scene, arr);
    if (id === 'none' || id === 'complain' || id === 'doubt') {
      var extra = pickFresh(scene, ensureStock());
      if (extra && line.indexOf(extra) === -1) line = line + ' ' + extra;
    }
    return line;
  }

