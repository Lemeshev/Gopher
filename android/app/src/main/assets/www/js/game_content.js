// Случайная подборка без повторов, с приоритетом на непросмотренные.
function shuffleArray(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function getContentPool(category) {
  const pool = CONTENT[category];
  if (!Array.isArray(pool) || pool.length === 0) return [];
  return pool;
}

// Вернуть count случайных предметов. seenIds — массив id просмотренных.
// Сначала берём непросмотренные, затем (если не хватает) — просмотренные.
function getRandomItems(category, count, seenIds) {
  const pool = getContentPool(category);
  if (pool.length === 0) return [];
  const seen = new Set(seenIds || []);
  const fresh = shuffleArray(pool.filter(it => !seen.has(contentId(category, it))));
  const old = shuffleArray(pool.filter(it => seen.has(contentId(category, it))));
  const picked = fresh.slice(0, count);
  if (picked.length < count) picked.push(...old.slice(0, count - picked.length));
  return picked.map(it => ({ emoji: it.e, name: it.n, fact: it.f, coins: it.coins, id: contentId(category, it) }));
}

// Стабильный id предмета. Принимает предмет ({ n }) или строку-название.
function contentId(category, item) {
  const name = typeof item === 'string' ? item : ((item && (item.n || item.name)) || '');
  return category + ':' + name;
}

// Сколько всего уникальных предметов в категории
function contentSize(category) {
  return getContentPool(category).length;
}

window.CONTENT = CONTENT;
window.getRandomItems = getRandomItems;
window.contentId = contentId;
window.contentSize = contentSize;
