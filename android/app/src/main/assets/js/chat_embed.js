  function findAlias(query) {
    var n = normalize(query);
    if (!n || n.length < 2) return null;
    var words = n.split(' ').filter(function(w) { return w && w.length >= 3; });
    var best = null;
    var bestScore = 0;
    Object.keys(ALIASES).forEach(function(id) {
      var aliases = ALIASES[id];
      var score = 0;
      var matchCount = 0;
      words.forEach(function(word) {
        var s = stem(word);
        aliases.forEach(function(alias) {
          if (word === alias || (s.length >= 3 && s === stem(alias))) {
            score += word.length >= 4 ? 3 : 2;
            matchCount++;
          } else if (alias.indexOf(word) !== -1 || word.indexOf(alias) !== -1) {
            score += 1;
            matchCount++;
          } else {
            var a = stem(alias);
            if (a.length >= 3 && s === a) {
              score += 2;
              matchCount++;
            }
          }
        });
      });
      if (matchCount > 0 && score > bestScore) {
        bestScore = score;
        best = id;
      }
    });
    return bestScore >= 3 ? best : null;
  }

