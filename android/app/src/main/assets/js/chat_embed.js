    var w = parts[parts.length - 1].replace(/[^A-Za-zА-Яа-яЁё-]/g, '');
    if (w.length < 2 || w.length > 16) return '';
    if (/ся$|сь$|ть$|ешь$|ишь$|ете$|лся$|лась$|лся$/.test(w.toLowerCase())) return '';
    return w.charAt(0).toUpperCase() + w.slice(1);
