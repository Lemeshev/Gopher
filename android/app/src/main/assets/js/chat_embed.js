  function mixVec(a, b, t) {
    var o = {};
    var k;
    a = a || {};
    b = b || {};
    for (k in a) o[k] = (a[k] || 0) * (1 - t);
    for (k in b) o[k] = (o[k] || 0) + b[k] * t;
    return o;
  }

